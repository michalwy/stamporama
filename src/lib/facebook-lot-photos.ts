import "server-only";
import sharp, { type OverlayOptions } from "sharp";
import { prisma } from "./db";
import { zip, type ZipEntry } from "./zip";
import { COLLAGE_MIME, COLLAGE_QUALITY_MAX, COLLAGE_QUALITY_MIN } from "./photos/collage";
import { normalizeCollageGridMode, normalizeCollageGridShape } from "./collage-template-rules";
import {
  buildFacebookPostPhotoArchive,
  OfferPhotoGenerationError,
  readOfferUploadSet,
} from "./offer-photo-generation";
import { facebookPostLayout, readFacebookGroupSettings } from "./facebook-auctions";
import { arrangeFacebookLotPhoto, lotPhotoSeparatorColor } from "./facebook-lot-photo-rules";
import { readFacebookFrozenLot } from "./facebook-post-rules";

// The photos of a captioned Facebook post (#1841; ADR-0061 §2 as amended): **one photo per lot**,
// its caption the lot's text. A lot whose upload set is one image contributes it as it is; a lot of
// several contributes them joined into one — fronts and backs as two halves of one grid with a
// separator, side by side or stacked toward the offer's collage shape. The arrangement is
// `facebook-lot-photo-rules.ts`'s; this module reads the images and draws it.
//
// Drawn on demand, never stored: the images it is made of are the offer's own, already stored and
// regenerated by the offer's photo run, so the joined one follows them without a second fingerprint
// to keep in step.

const DEFAULT_BACKGROUND = "#000000";

/** One lot's photo: the bytes and the name it is downloaded under. */
export interface FacebookLotPhoto {
  fileName: string;
  mime: string;
  bytes: Buffer;
}

/** The offer's collage settings and its platform's output limits, as the joined image is drawn with. */
async function readLotPhotoStyle(offerId: string) {
  const offer = await prisma.offer.findUniqueOrThrow({
    where: { id: offerId },
    select: {
      collageGridMode: true,
      collageGridShape: true,
      collageColumns: true,
      collageGapPercent: true,
      collageBackground: true,
      platform: { select: { maxPhotoEdge: true, maxPhotoFileSizeMib: true } },
    },
  });
  return {
    collage: {
      gridMode: normalizeCollageGridMode(offer.collageGridMode),
      gridShape: normalizeCollageGridShape(offer.collageGridShape),
      columns: offer.collageColumns ?? 1,
      gapPercent: offer.collageGapPercent ?? 0,
    },
    background: offer.collageBackground ?? DEFAULT_BACKGROUND,
    maxEdge: offer.platform?.maxPhotoEdge ?? null,
    maxBytes: offer.platform?.maxPhotoFileSizeMib != null ? offer.platform.maxPhotoFileSizeMib * 1024 * 1024 : null,
  };
}

/**
 * A lot's one photo (#1841), owner-checked through the photo read model. Its only image as it is, or
 * its images joined. The name leads with the offer's number (#1754), as every file of an offer does.
 *
 * @throws {OfferPhotoGenerationError} when the offer has no images to upload.
 */
export async function renderFacebookLotPhoto(ownerId: string, offerId: string): Promise<FacebookLotPhoto> {
  const set = await readOfferUploadSet(ownerId, offerId);
  if ("reason" in set) throw new OfferPhotoGenerationError(set.reason);
  const style = await readLotPhotoStyle(offerId);
  const arrangement = arrangeFacebookLotPhoto(set.images, style.collage)!;
  if (arrangement.kind === "asIs") {
    const image = set.images[arrangement.image];
    return { fileName: `${set.slug}.${image.fileName.split(".").pop()}`, mime: image.mime, bytes: image.bytes };
  }

  const layers: OverlayOptions[] = [];
  for (const placement of arrangement.placements) {
    const image = set.images[placement.image];
    // Decoded at the size the read model states, so a stored image of another size still sits in its
    // cell rather than spilling over the next.
    const input = await sharp(image.bytes, { failOn: "error" })
      .rotate()
      .resize(image.width, image.height, { fit: "inside" })
      .toBuffer();
    layers.push({ input, left: placement.x, top: placement.y });
  }
  if (arrangement.separator) {
    const { x, y, width, height } = arrangement.separator;
    layers.push({
      input: {
        create: { width, height, channels: 3, background: lotPhotoSeparatorColor(style.background) },
      },
      left: x,
      top: y,
    });
  }
  const canvas = await sharp({
    create: { width: arrangement.width, height: arrangement.height, channels: 3, background: style.background },
  })
    .composite(layers)
    .raw()
    .toBuffer({ resolveWithObject: true });

  // The platform's limits, as every offer image keeps them (#308): the longest edge, then the file
  // size by stepping the quality down — the joined image is made of images already within them, so
  // a handful of steps is all it can need.
  const edge = Math.min(Math.max(canvas.info.width, canvas.info.height), style.maxEdge ?? Infinity);
  let bytes = Buffer.alloc(0);
  for (let quality = COLLAGE_QUALITY_MAX; quality >= COLLAGE_QUALITY_MIN; quality -= 10) {
    bytes = await sharp(canvas.data, {
      raw: { width: canvas.info.width, height: canvas.info.height, channels: canvas.info.channels },
    })
      .resize(edge, edge, { fit: "inside", withoutEnlargement: true })
      .jpeg({ quality })
      .toBuffer();
    if (style.maxBytes == null || bytes.byteLength <= style.maxBytes) break;
  }
  return { fileName: `${set.slug}.jpg`, mime: COLLAGE_MIME, bytes };
}

/** The post a lot belongs to, owner-checked, with its lots in order and how it is laid out now. */
async function readPost(ownerId: string, postId: string) {
  const post = await prisma.facebookPost.findFirst({
    where: { id: postId, collection: { ownerId } },
    select: {
      id: true,
      layout: true,
      groupId: true,
      lots: {
        orderBy: { facebookLotNo: "asc" },
        select: { id: true, facebookLotNo: true, facebookPostSnapshot: true },
      },
    },
  });
  if (!post) throw new OfferPhotoGenerationError("Post not found.");
  return post;
}

/**
 * A lot's one photo, read for a post (#1841) — refused unless the offer is a lot of that post, so the
 * card's address cannot be turned into a read of another offer.
 */
export async function renderFacebookPostLotPhoto(
  ownerId: string,
  postId: string,
  offerId: string
): Promise<FacebookLotPhoto> {
  const post = await readPost(ownerId, postId);
  if (!post.lots.some((lot) => lot.id === offerId)) {
    throw new OfferPhotoGenerationError("That offer is not a lot of this post.");
  }
  return renderFacebookLotPhoto(ownerId, offerId);
}

/** How a post is laid out as its photos are downloaded: as it was published, read off its last lot's
 *  frozen text (#1800), else as it is set now — the card's own rule. */
async function postPhotoLayout(post: Awaited<ReturnType<typeof readPost>>) {
  const frozen = readFacebookFrozenLot(post.lots.at(-1)?.facebookPostSnapshot);
  if (frozen) return frozen.layout;
  return facebookPostLayout(post, await readFacebookGroupSettings(post.groupId));
}

/**
 * A post's photos as one ZIP, in lot order (#1544, #1841). A captioned post gives **one photo per
 * lot**, named `lot-01-<offer>.jpg`…; a post laid out in its text gives every lot's upload set as
 * before (`buildFacebookPostPhotoArchive`). A lot with nothing to upload is left out; the archive is
 * refused only when no lot has anything.
 */
export async function buildFacebookPostPhotos(
  ownerId: string,
  postId: string
): Promise<{ fileName: string; bytes: Buffer }> {
  const post = await readPost(ownerId, postId);
  if ((await postPhotoLayout(post)) !== "captions") return buildFacebookPostPhotoArchive(ownerId, postId);
  const entries: ZipEntry[] = [];
  for (const [index, lot] of post.lots.entries()) {
    let photo: FacebookLotPhoto;
    try {
      photo = await renderFacebookLotPhoto(ownerId, lot.id);
    } catch (err) {
      if (err instanceof OfferPhotoGenerationError) continue;
      throw err;
    }
    const prefix = `lot-${String(lot.facebookLotNo ?? index + 1).padStart(2, "0")}`;
    entries.push({ name: `${prefix}-${photo.fileName}`, contents: photo.bytes });
  }
  if (entries.length === 0) {
    throw new OfferPhotoGenerationError("None of this post's lots has images to upload — generate them first.");
  }
  return { fileName: `facebook-post-${post.lots.length}-lots-photos.zip`, bytes: zip(entries) };
}
